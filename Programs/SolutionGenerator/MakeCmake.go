type CmakeConfigurePresetCacheVariable struct {
    Name  string
    Value string
}

func (variable *CmakeConfigurePresetCacheVariable) ToJson(indent int, b *strings.Builder) {
    if b == nil {
        panic("builder is nil")
    }
    Wwinnl(b, indent, fmt.Sprintf("\"%s\": \"%s\"", variable.Name, variable.Value))
    return
}

type CmakeConfigurePresetEnvironment struct {
    Key   string
    Value string
}

type CmakeConfigurePreset struct {
    Name           string
    FriendlyName   string
    Generator      string
    BinaryDir      string
    CacheVariables []CmakeConfigurePresetCacheVariable
    Environment    []CmakeConfigurePresetEnvironment
}

func (preset *CmakeConfigurePreset) ToJson(b *strings.Builder) {
    if b == nil {
        panic("builder is nil")
    }

    Wwi(b, 2, "{")
    Wwi(b, 3, fmt.Sprintf("\"name\": \"%s\",", preset.Name))
    Wwi(b, 3, fmt.Sprintf("\"displayName\": \"%s\",", preset.FriendlyName))
    Wwi(b, 3, fmt.Sprintf("\"generator\": \"%s\",", preset.Generator))
    Wwi(b, 3, fmt.Sprintf("\"binaryDir\": \"%s\",", preset.BinaryDir))
    Wwi(b, 3, "\"cacheVariables\": {")
    for idx, _ := range preset.CacheVariables {
       preset.CacheVariables[idx].ToJson(4, b)
       if idx < len(preset.CacheVariables)-1 {
           Wni(b, ",")
       } else {
           Wni(b, "")
       }
    }
    Wwi(b, 3, "},")
    Wwi(b, 3, "\"environment\": {")
    for idx, _ := range preset.Environment {
        Wwinnl(b, 4, fmt.Sprintf("\"%s\": \"%s\"", preset.Environment[idx].Key, preset.Environment[idx].Value))
        if idx < len(preset.Environment)-1 {
            Wni(b, ",")
        } else {
            Wni(b, "")
        }
    }
    Wwi(b, 3, "}")
    Wwinnl(b, 2, "}")

    return
}

