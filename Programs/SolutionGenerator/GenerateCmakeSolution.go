func GenerateConfigurationPreset(builder *strings.Builder, platform string, buildType string, targetSuffix string) {
    var realPlatform string = platform
    if strings.Contains(platform, " ") {
        realPlatform = platform[:strings.Index(platform, " ")]
    }

    var WindowsPreset CmakeConfigurePreset = CmakeConfigurePreset{
        Name: fmt.Sprintf("%s-%s-%s", strings.ToLower(strings.ReplaceAll(platform, " ", "-")), strings.ToLower(buildType), strings.ToLower(targetSuffix)),
        FriendlyName: fmt.Sprintf("%s | %s-%s", platform, buildType, targetSuffix),
        Generator: "MinGW Makefiles",
        CacheVariables: []CmakeConfigurePresetCacheVariable{
            CmakeConfigurePresetCacheVariable{
                Name: "TARGET_PLATFORM",
                Value: realPlatform,
            },
            CmakeConfigurePresetCacheVariable{
                Name: "CMAKE_BUILD_TYPE",
                Value: fmt.Sprintf("%s-%s", buildType, targetSuffix),
            },
        },
    }
    WindowsPreset.ToJson(builder)

    return
}
