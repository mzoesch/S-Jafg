type CmakeConfigurePresetCacheVariable struct {
    Name string
    Value string
}

func (variable *CmakeConfigurePresetCacheVariable) ToJson(indent int, builder *strings.Builder) {
    if builder == nil {
        panic("builder is nil")
    }

    WriteWithIndent(builder, indent, fmt.Sprintf("\"%s\": \"%s\"", variable.Name, variable.Value))

    return
}

type CmakeConfigurePreset struct {
    Name string
    FriendlyName string
    Generator string
    CacheVariables []CmakeConfigurePresetCacheVariable
}

func (preset *CmakeConfigurePreset) ToJson(builder *strings.Builder) {
    if builder == nil {
        panic("builder is nil")
    }

    WriteWithIndent(builder, 8, "{\n")
    WriteWithIndent(builder, 12, fmt.Sprintf("\"name\": \"%s\",\n", preset.Name))
    WriteWithIndent(builder, 12, fmt.Sprintf("\"displayName\": \"%s\",\n", preset.FriendlyName))
    WriteWithIndent(builder, 12, fmt.Sprintf("\"generator\": \"%s\",\n", preset.Generator))
    WriteWithIndent(builder, 12, "\"cacheVariables\": {\n")
    for idx, _ := range preset.CacheVariables {
        preset.CacheVariables[idx].ToJson(16, builder)
        if idx < len(preset.CacheVariables) - 1 {
            builder.WriteString(",")
        }
        builder.WriteString("\n")
    }
    WriteWithIndent(builder, 12, "}\n")
    WriteWithIndent(builder, 8, "}")

    return
}

