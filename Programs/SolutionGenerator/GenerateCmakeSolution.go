func WriteCmakeFileVendorSection(builder *strings.Builder) {
    // This is absolutely hard-coded but who gives.
    WriteWithIndent(builder, 0, "\n")
    WriteWithIndent(builder, 0, "############################\n")
    WriteWithIndent(builder, 0, "# Vendor\n")
    WriteWithIndent(builder, 0, "############################\n")
    WriteWithIndent(builder, 0, "file(GLOB_RECURSE Vendor_SRC_FILES\n")
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.md\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.jafgmod\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.jafgproj\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.h\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.hpp\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.c\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 4, fmt.Sprintf("\"${CMAKE_SOURCE_DIR}/%s/**.cpp\"\n", Shared.VendorIncludeDir))
    WriteWithIndent(builder, 0, ")\n")
    WriteWithIndent(builder, 0, "source_group(\"Vendor\" FILES ${Vendor_SRC_FILES})\n")
    WriteWithIndent(builder, 0, "add_custom_target(Vendor SOURCES ${Vendor_SRC_FILES})\n")
    WriteWithIndent(builder, 0, "set_target_properties(Vendor PROPERTIES FOLDER \"Vendor\")\n")

    return
}
