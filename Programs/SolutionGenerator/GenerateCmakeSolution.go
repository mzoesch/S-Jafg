func WriteCmakeFileProjectSpecificSections(builder *strings.Builder) {
    if builder == nil {
        panic("WriteCmakeFileProjectSpecificSections called with nil builder.")
    }

    for idx, _ := range Shared.GApp.Projects {
        var project *Shared.Project = &Shared.GApp.Projects[idx]
        WriteCmakeFileForSpecificProject(builder, 0, project)
    }

    return
}

func WriteCmakeFileForSpecificProject(builder *strings.Builder, indent int, project *Shared.Project) {
    if builder == nil {
        panic("WriteCmakeFileForSpecificProject called with nil builder.")
    }
    if project == nil {
        panic("WriteCmakeFileForSpecificProject called with nil project.")
    }

    for idx, _ := range project.Modules {
        var module *Shared.Module = &project.Modules[idx]
        WriteCmakeFileForSpecificModule(builder, indent, module)
    }

    return
}

func GetAllUniqueBuildConfigurations() []string {
    var out []string = []string{}
    var targs []Shared.Target = Shared.GApp.GetAllUniqueTargets()
    for idx, _ := range targs {
        var targ *Shared.Target = &targs[idx]

        out = append(out, fmt.Sprintf("Debug-%s", targ.GetSuffix()))
        out = append(out, fmt.Sprintf("Development-%s", targ.GetSuffix()))
        out = append(out, fmt.Sprintf("Shipping-%s", targ.GetSuffix()))

        continue
    }

    return out
}

func GetAllUniqueDebugBuildConfigurations() []string {
    var out []string = []string{}

    for _, targ := range GetAllUniqueBuildConfigurations() {
        if strings.Contains(targ, "Debug") {
            out = append(out, targ)
        }

        continue
    }

    return out
}

